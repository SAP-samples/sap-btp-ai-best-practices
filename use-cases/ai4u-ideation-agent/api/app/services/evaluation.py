"""AI Evaluation Service for ideation solutions.

Uses SAP GenAI Hub Orchestration v2 (Gemini 2.5 Flash) to score and evaluate
AI solution proposals generated by the ideation agent.
"""

from __future__ import annotations

import json
import logging
import time
from typing import Any, Dict, List, Optional

logger = logging.getLogger(__name__)

MODEL_NAME = "gemini-2.5-flash"
TEMPERATURE = 0.2


SYSTEM_PROMPT = """You are a witty, quirky, and honest AI solution evaluator. Your job is to evaluate AI use-case proposals for real-world business challenges.

These proposals will be fed into Joule Studio (SAP's intent-based development platform) as the starting "intent" — Joule then generates requirements, technical specs, and code. Your evaluation measures how well-defined and actionable the intent is for Joule Studio to work with.

You are a TOUGH but fair grader. Most proposals are decent ideas but lack the specificity Joule needs. Score them accordingly.

## What Users Submit

1. Industry
2. Problem Statement
3. Proposed Solution (title + detailed description)
4. Application Type (Agent or Application)
5. Company Context (if available)

## Scoring Rubric (1-1000)

**900-1000 – Joule-ready production intent**
The proposal is a complete, deployable intent specification. ALL workflow branches have defined endpoints. ALL failure modes are handled with specific recovery/escalation paths. The complete escalation lifecycle is defined (what happens when escalation itself doesn't resolve — timeout, re-escalation, fallback). Data structures are described precisely (flat vs hierarchical, key fields, relationships). Every user interaction at every decision point is specified. Joule could generate a full PRD from this without asking a single clarifying question. Achieved only after thorough refinement.

**800-899 – Complete intent, minor polish needed**
All major workflow branches are defined, including the primary failure paths (extraction fails, system unavailable, data malformed). Escalation paths exist with clear owners. Decision logic is fully described at each routing point. User interactions at most decision points are specified. May still be missing: secondary failure modes (timeout during escalation, partial data scenarios), complete data structure descriptions, or edge-case branch endpoints. Joule could generate a solid PRD with at most 1-2 minor clarifications.

**650-799 – Strong foundation, needs depth**
Well-structured proposal with a clear end-to-end workflow. Names specific systems, user roles, and triggers. Describes the happy path clearly with basic decision logic (e.g., confidence-based routing concept). May include one failure path. This is where a well-produced first draft lands — it has the WHAT and WHO nailed, but hasn't deeply explored WHAT GOES WRONG. Joule could start working but would need to ask several "but what happens when X?" questions.

**450-649 – Solid concept, needs sharpening**
Describes the workflow at a high level with some specifics. May name systems but not describe the data flow between them. May mention user roles generically. Trigger is stated but process steps are vague. Decision logic is mentioned but not fully articulated. Failure paths are absent or hand-waved ("handle errors gracefully"). A proposal at this level reads like a good elevator pitch, not a specification.

**250-449 – Underdeveloped**
Identifies a real problem and proposes "AI" as a solution, but is vague on the actual workflow. No named systems, no specific user roles, no defined trigger, no decision logic. Could apply to many companies without modification. Joule Studio would struggle to generate any meaningful requirements from this.

**1-249 – Off-target**
AI isn't appropriate, logic is flawed, or the proposal doesn't make coherent sense.

## Evaluation Criteria (weighted)

1. **Process Specificity (25%)**: Is the business process described concretely? Specific triggers, steps, data flows, and outputs? Or is it abstract?
2. **Problem-Solution Fit (20%)**: Does the AI approach logically address the stated problem? Is the solution type (Agent/Application/Workflow) appropriate?
3. **Integration Context (20%)**: Are relevant systems and data sources identified by name (e.g., "S/4HANA", "SharePoint", "email inbox")? Note: naming the system and the business operation is sufficient — specific API endpoints, BAPIs, or transaction codes are implementation details that Joule discovers automatically. Do NOT penalize for missing APIs.
4. **Decision Completeness & Edge Cases (15%)**: Is every workflow branch defined? Are failure paths and exception handling addressed? Is routing logic clear — what happens at each decision point? Are human-in-the-loop touchpoints specified where needed? The key test: could Joule generate a PRD from this without asking "but what happens when X?"
5. **User Roles & Personas (10%)**: Are the people involved clearly identified — who triggers the process, who approves, who benefits? Are their workflows described?
6. **Business Context (10%)**: Is the business pain described with enough context to understand scale and urgency? Quantification (volume, time, error rate) strengthens the proposal but is not required — the key question is whether Joule can infer the scope of the problem from context.

## Calibration Rules

- The MEDIAN score for a first-time well-produced proposal (with named systems, user roles, trigger, and basic decision logic but minimal failure handling) should be 680-720. This is the expected landing zone for proposals produced by the ideation agent after a full interview.
- A proposal that says "use AI to extract data from PDFs and update the system" without specifying WHICH system, WHO uses it, WHAT triggers it, or WHAT happens on failure is a 400-520.
- A proposal with a clear happy-path workflow, named systems, named roles, and a defined trigger but NO failure paths and NO edge-case handling is a 650-720 — not higher, regardless of how polished the happy path reads.
- A proposal with NO defined failure paths (what happens when extraction fails, systems are down, data is missing or malformed) cannot score above 780, regardless of how clean the happy path is. This is the primary ceiling separating first drafts from refined intents.
- A proposal with only ONE failure path defined (e.g., "low confidence → human review") but no handling of system failures, data quality issues, or timeout scenarios is capped at 830.
- A proposal missing a complete escalation lifecycle (what happens when the escalation itself doesn't resolve — timeout, re-escalation to a different owner, automated fallback) cannot score above 870.
- Scores above 900 require ALL of: (a) every workflow branch has a defined endpoint, (b) multiple failure modes handled with specific recovery actions, (c) complete escalation lifecycle including timeout/re-escalation, (d) data structures described with enough precision for Joule to infer a schema, (e) user interactions specified at every decision point.
- Mentioning "human-in-the-loop for low confidence" is good (+20-30 from baseline). It's even better if the routing logic is described clearly (what happens at high vs low confidence, who reviews, what actions they can take, what happens if reviewer doesn't act within a timeframe).
- Adding buzzword technologies without explaining WHY they fit or HOW they integrate adds at most 10-20 points.
- Quantifying the pain ("50-200 PDFs/week, 15 min each, 8% error rate") is a nice bonus (+10-20) that helps Joule size the solution, but is far less important than describing complete decision logic and failure paths.
- Naming specific user roles ("procurement clerks assign groups, team leads approve exceptions") is far better than "users review the output" (+20-30 over generic role descriptions).
- Do NOT suggest or penalize for missing: specific API endpoints, BAPIs, transaction codes, UI wireframes, or deployment configurations. Joule discovers these automatically. The intent level only needs to name the system and the business operation.
- Each additional fully-defined failure path (with specific recovery action and owner) should add 30-50 points above the baseline happy-path score.
- Each additional workflow branch with a defined endpoint should add 20-40 points.
- Data structure precision (flat vs hierarchy, key fields, relationships) adds 20-30 points.

## Suggestion Rules

- Suggestions MUST be phrased as questions the user can directly answer (they become clickable chips that trigger a refinement conversation).
- Good: "What should happen when the AI's confidence is too low to auto-assign?" / "How is your Excel taxonomy structured — flat list or hierarchical groups?"
- Bad: "Quantify the current manual effort" / "Add exception handling" / "Specify the confidence threshold"
- Focus on gaps that prevent Joule from generating a PRD without clarifying questions: missing workflow branches, undefined failure/exception paths, unclear data structures, ambiguous routing logic, unspecified user interactions at decision points.
- NEVER suggest specifying: API endpoints, BAPIs, transaction codes, specific threshold numbers, UI wireframes, deployment configs, or implementation frameworks. Joule discovers these automatically.
- NEVER ask for something the rubric marks as optional or bonus.
- Always provide exactly 3 suggestions:
  - Suggestions 1-2: Gap-filling questions about missing workflow branches, failure paths, data structures, or routing logic.
  - Suggestion 3: A creative "what if" question that challenges the user's framing, suggests an unexpected extension, or opens a direction they haven't considered. This is the ideation spark — think lateral, not incremental. E.g. "What if the AI could also flag pricing anomalies across suppliers while it's reading the quotations?"
- Each suggestion must target a DIFFERENT aspect. Never repeat the same gap in different words.

## Output Format

Respond with a purely JSON object (no markdown formatting):
{
    "score": <integer 1-1000>,
    "feedback": "<Short, witty, and punchy headline (max 8 words, e.g., 'Nailed It!', 'Nice idea, where's the detail?', 'You're on to something...'). Do not use emojis.>",
    "detailedAnalysis": "<Directly address the user (e.g., 'Your proposal...'). Use Markdown formatting. Bold (**text**) for emphasis, bullet points (- item) for lists. Quirky, humorous, slightly blunt persona. Tell it like it is. Be specific about WHAT is missing to score higher — what would Joule Studio need to know? Keep under 100 words, max 3 bullet points. NO emojis.>",
    "suggestions": ["<Gap-filling QUESTION about a missing workflow branch, failure path, or ambiguous routing logic>", "<Another gap-filling QUESTION targeting a DIFFERENT aspect>", "<A creative 'what if' QUESTION that challenges the framing or suggests an unexpected extension the user hasn't considered>"],
    "appropriatenessLevel": "<Map to score: 750+ = 'excellent', 550-749 = 'good', 350-549 = 'fair', below 350 = 'needs-improvement'>"
}
"""


def _orchestration_imports() -> Dict[str, Any]:
    from gen_ai_hub.orchestration_v2.models.config import ModuleConfig, OrchestrationConfig
    from gen_ai_hub.orchestration_v2.models.llm_model_details import LLMModelDetails
    from gen_ai_hub.orchestration_v2.models.message import SystemMessage, UserMessage
    from gen_ai_hub.orchestration_v2.models.template import (
        PromptTemplatingModuleConfig,
        Template,
    )
    from gen_ai_hub.orchestration_v2.service import OrchestrationService

    return {
        "ModuleConfig": ModuleConfig,
        "OrchestrationConfig": OrchestrationConfig,
        "LLMModelDetails": LLMModelDetails,
        "SystemMessage": SystemMessage,
        "UserMessage": UserMessage,
        "PromptTemplatingModuleConfig": PromptTemplatingModuleConfig,
        "Template": Template,
        "OrchestrationService": OrchestrationService,
    }


def _build_user_prompt(
    *,
    industry: str,
    title: str,
    problem: str,
    solution: str,
    app_type: str,
    company_context: Optional[str] = None,
) -> str:
    """Build the user prompt from the ideation solution fields."""
    parts = [
        f"Industry: {industry}",
        f"Solution Title: {title}",
        f"Problem Statement:\n{problem}",
        f"Proposed Solution:\n{solution}",
        f"Application Type: {app_type}",
    ]
    if company_context:
        parts.append(f"Company Context:\n{company_context}")
    parts.append("\nEvaluate this AI solution proposal based on the criteria.")
    return "\n\n".join(parts)


def _extract_message_content(result: Any) -> str:
    """Extract text content from orchestration result.

    Handles both string content and list-of-TextPart content shapes.
    """
    final_result = getattr(result, "final_result", None)
    choices = getattr(final_result, "choices", None)
    if isinstance(choices, list) and choices:
        first_choice = choices[0]
        message = getattr(first_choice, "message", None)
        if message:
            content = getattr(message, "content", "") or ""
            # content can be str or List[TextPart]
            if isinstance(content, str):
                return content.strip()
            if isinstance(content, list):
                # List of TextPart objects with .text attribute
                parts = []
                for part in content:
                    text = getattr(part, "text", None) or str(part)
                    parts.append(text)
                return "".join(parts).strip()
            return str(content).strip()
    return ""


def evaluate_solution(
    *,
    industry: str,
    title: str,
    problem: str,
    solution: str,
    app_type: str = "Agent",
    company_context: Optional[str] = None,
    context_id: str = "",
) -> Dict[str, Any]:
    """Evaluate an ideation solution using Gemini 2.5 Flash.

    Returns a dict with: score, feedback, detailedAnalysis, suggestions,
    appropriatenessLevel, success, error.
    """
    from app.observability.llm_usage_logging import LLMUsageMeta, emit_llm_usage_event, emit_llm_usage_for_response

    imports = _orchestration_imports()
    Template = imports["Template"]
    SystemMessage = imports["SystemMessage"]
    UserMessage = imports["UserMessage"]
    LLMModelDetails = imports["LLMModelDetails"]
    PromptTemplatingModuleConfig = imports["PromptTemplatingModuleConfig"]
    ModuleConfig = imports["ModuleConfig"]
    OrchestrationConfig = imports["OrchestrationConfig"]
    OrchestrationService = imports["OrchestrationService"]

    user_prompt = _build_user_prompt(
        industry=industry,
        title=title,
        problem=problem,
        solution=solution,
        app_type=app_type,
        company_context=company_context,
    )

    template = Template(
        template=[
            SystemMessage(content=SYSTEM_PROMPT),
            UserMessage(content=user_prompt),
        ]
    )
    llm = LLMModelDetails(
        name=MODEL_NAME,
        params={
            "temperature": TEMPERATURE,
            "response_format": {"type": "json_object"},
        },
    )
    prompt_template = PromptTemplatingModuleConfig(prompt=template, model=llm)
    config = OrchestrationConfig(modules=ModuleConfig(prompt_templating=prompt_template))
    service = OrchestrationService(config=config)

    meta = LLMUsageMeta(
        route="/api/ideation-agent/evaluate",
        method="POST",
        correlation_id=context_id or None,
    )
    started = time.perf_counter()

    try:
        result = service.run()
    except Exception as exc:
        latency_ms = int((time.perf_counter() - started) * 1000)
        emit_llm_usage_event(
            route=meta.route,
            method=meta.method,
            provider="sap-ai-core",
            model=MODEL_NAME,
            llm_endpoint="orchestration",
            input_tokens=0,
            output_tokens=0,
            outcome="error",
            latency_ms=latency_ms,
            correlation_id=meta.correlation_id,
            step_name="ideation_agent.evaluation",
            feature="evaluation",
        )
        logger.error("Evaluation orchestration call failed: %s", exc)
        return {
            "score": 500,
            "feedback": "Evaluation Error",
            "detailedAnalysis": "We couldn't process the AI evaluation at this time. Please try again later.",
            "suggestions": [],
            "appropriatenessLevel": "fair",
            "success": False,
            "error": str(exc),
        }

    latency_ms = int((time.perf_counter() - started) * 1000)
    emit_llm_usage_for_response(
        result,
        meta=meta,
        provider="sap-ai-core",
        model=MODEL_NAME,
        llm_endpoint="orchestration",
        latency_ms=latency_ms,
        step_name="ideation_agent.evaluation",
        feature="evaluation",
    )

    content = _extract_message_content(result)
    if not content:
        logger.error("Evaluation returned empty content")
        return {
            "score": 500,
            "feedback": "Evaluation Error",
            "detailedAnalysis": "The evaluation returned an empty response. Please try again.",
            "suggestions": [],
            "appropriatenessLevel": "fair",
            "success": False,
            "error": "Empty response from LLM",
        }

    try:
        evaluation_data = json.loads(content)
    except json.JSONDecodeError as exc:
        logger.error("Failed to parse evaluation JSON: %s | content: %s", exc, content[:500])
        return {
            "score": 500,
            "feedback": "Evaluation Error",
            "detailedAnalysis": "We couldn't process the AI evaluation. Please try again.",
            "suggestions": [],
            "appropriatenessLevel": "fair",
            "success": False,
            "error": "Invalid JSON response from LLM",
        }

    return {
        "score": int(evaluation_data.get("score", 500)),
        "feedback": str(evaluation_data.get("feedback", "Assessment Complete")),
        "detailedAnalysis": str(evaluation_data.get("detailedAnalysis", "")),
        "suggestions": list(evaluation_data.get("suggestions", [])),
        "appropriatenessLevel": str(evaluation_data.get("appropriatenessLevel", "good")),
        "success": True,
        "error": None,
    }
