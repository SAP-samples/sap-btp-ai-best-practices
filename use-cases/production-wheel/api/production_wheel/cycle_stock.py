"""Cycle stock strategy of a subgroup: single RoC or runner multiples (managed complexity).

A subgroup (candidate group) is produced in one cycle: every batch of its SEFI is
filled into its FINIs. Its wheel RoC ``R`` (whole days, ``production_wheel.wheel_roc``)
is the "base" of the strategy.

- ``single``: every FINI is filled in every batch and gets ``R``.
  Changeovers per batch = FINIs - 1. This is the tool's historical behaviour.
- ``runner_multiple``: the fastest FINI keeps ``R``; every other FINI ``i``
  is filled only every ``k_i``-th batch (``runners.runner_multiple``, computed
  from ``R``), so it gets ``R * k_i`` days. On average a batch is filled into
  ``sum(1 / k_i)`` FINIs, so changeovers per batch = ``sum(1 / k_i) - 1``.

Pallets never enter ``R``, the multiples, the batches per week or the
changeovers; they only raise the inventory RoC of each FINI
(``wheel_roc.inventory_roc_days``).

The optimizer sees a ``runner_multiple`` subgroup as a second version of the
same candidate (same members and PV, ``cycle_stock_strategy="runner_multiple"``,
its own ``candidate_hash``). Both versions cover the same FINIs, so the exact
cover allows at most one of them. ``expand_strategy_variants`` creates the
versions from the plant profile's ``CycleStockPolicy.mode``; the solver,
validation, reporting and business-rule facts all call ``strategy_figures`` so
they agree on coverage and ``J_CH``.

Worked example (``R`` = 10 days, 5 days per week so 0.5 batches per week,
demand 4000/1600/690/160 L, multiples 1/2/2/4): single J_CH = 0.5 * 3 = 1.5,
wheel coverage 10.0; runner multiples J_CH = 0.5 * (2.25 - 1) = 0.625,
demand-weighted wheel coverage = 14.29.

Self-check::

    cd api && ../.venv/bin/python -m production_wheel.cycle_stock
"""

from __future__ import annotations

import dataclasses
from collections.abc import Mapping, Sequence
from dataclasses import dataclass

from production_wheel.business_rules import group_allowed, runner_coverage
from production_wheel.candidates.models import Candidate, CandidateMember, stable_hash
from production_wheel.runners import block_minimum, classify, excel_round, runner_multiple
from production_wheel.wheel_roc import WheelFigures, wheel_figures

SINGLE = "single"
RUNNER_MULTIPLE = "runner_multiple"
# Statuses of runners.runner_multiple whose multiple is used; any other keeps the base (multiple 1).
_USABLE = frozenset({"reference_runner", "adjusted"})


@dataclass(frozen=True, slots=True)
class MemberMultiple:
    """How one FINI of a subgroup shares the subgroup's batches.

    Attributes:
        fini_id: FINI identifier.
        runner_class: ``"high"``, ``"medium"``, ``"low"`` or ``None``.
        full_batch_days: Days one full SEFI batch covers for this FINI alone.
        group_ratio: ``full_batch_days`` / the subgroup's smallest, Excel-rounded to 1 decimal.
        multiple: Batches one fill must cover (1 = filled every batch).
        status: ``runners.runner_multiple`` status; unusable statuses keep multiple 1.
    """

    fini_id: str
    runner_class: str | None
    full_batch_days: float | None
    group_ratio: float | None
    multiple: int
    status: str


@dataclass(frozen=True, slots=True)
class StrategyFigures:
    """Coverage and changeover figures of one subgroup under its strategy.

    Attributes:
        strategy: ``"single"`` or ``"runner_multiple"``.
        coverage_days: Subgroup coverage under the run's ``coverage_basis``.
        j_ch: Weekly changeover contribution under the strategy.
        fills_per_batch: Average FINIs filled per batch (``sum(1 / k)``).
        members: Per-FINI multiples, in the subgroup's member order.
        wheel: Every wheel figure (``R``, batches per week, FINI wheel and
            inventory RoC, coverage under each basis).
    """

    strategy: str
    coverage_days: float
    j_ch: float
    fills_per_batch: float
    members: tuple[MemberMultiple, ...]
    wheel: WheelFigures

    @property
    def max_multiple(self) -> int:
        """Return the largest multiple; 1 means the strategy changes nothing."""

        return max((member.multiple for member in self.members), default=1)

    @property
    def frequency_per_week(self) -> float:
        """Return the subgroup's batches per week (``days per week / R``)."""

        return self.wheel.frequency_per_week

    def member_coverage(self) -> dict[str, float]:
        """Return ``{fini_id: R * multiple}``, each FINI's wheel RoC under the strategy."""

        return dict(zip(self.wheel.fini_ids, self.wheel.fini_wheel_roc_days))


def variant_hash(candidate: Candidate) -> str:
    """Return the identity of the ``runner_multiple`` version of a single candidate.

    Args:
        candidate: A candidate generated by the pool (``single`` strategy).

    Returns:
        A digest distinct from ``candidate.candidate_hash`` and stable across runs.
    """

    return stable_hash({"candidate_hash": candidate.candidate_hash, "cycle_stock_strategy": RUNNER_MULTIPLE})


def multiple_version(candidate: Candidate) -> Candidate:
    """Return the ``runner_multiple`` version of a pool candidate (same members, PV and line)."""

    return dataclasses.replace(candidate, cycle_stock_strategy=RUNNER_MULTIPLE, candidate_hash=variant_hash(candidate))


def member_multiples(
    members: Sequence[CandidateMember],
    base_days: float,
    batch_litres: float,
    config,
    ratios: Mapping[tuple[str, str, str], float | None],
) -> tuple[MemberMultiple, ...]:
    """Return the runner multiple of every FINI of one subgroup.

    Args:
        members: The subgroup's FINIs.
        base_days: The subgroup's wheel RoC ``R`` in whole days (``wheel_roc.wheel_roc_days``).
        batch_litres: Effective batch of the subgroup's PV (``candidate_pv`` runner basis).
        config: Run configuration (runner thresholds, basis, cycle stock policy).
        ratios: ``business_rules.runner_ratios`` over the whole population, for the class.

    Returns:
        One ``MemberMultiple`` per member, same order.
    """

    full = [runner_coverage(member, config, batch_litres) for member in members]
    smallest = block_minimum(full)
    result = []
    for member, days in zip(members, full):
        positive = days is not None and days > 0
        group_ratio = excel_round(days / smallest, 1) if positive and smallest else None
        runner = classify(days, ratios.get((*member.block_key, member.fini_id)), config.runner_thresholds)
        multiple, status = runner_multiple(base_days, group_ratio, days, runner, config.cycle_stock_policy)
        result.append(MemberMultiple(member.fini_id, runner, days, group_ratio,
                                     multiple if status in _USABLE else 1, status))
    return tuple(result)


def strategy_figures(
    strategy: str,
    members: Sequence[CandidateMember],
    nominal_lot_litres: float,
    effective_batch_litres: float,
    config,
    ratios: Mapping[tuple[str, str, str], float | None],
    classify_members: bool = True,
) -> StrategyFigures:
    """Return coverage and ``J_CH`` of one subgroup under a cycle stock strategy.

    Args:
        strategy: ``"single"`` or ``"runner_multiple"``.
        members: The subgroup's FINIs.
        nominal_lot_litres: Nominal lot of the subgroup's PV (pallets per batch).
        effective_batch_litres: Effective batch of the subgroup's PV (RoC).
        config: Run configuration (demand days, productive weeks, coverage
            basis, runner thresholds and cycle stock policy).
        ratios: ``business_rules.runner_ratios`` of the whole population.
        classify_members: For ``single``, also return each FINI's runner class
            (reporting and validation need it; the solver's hot path does not).

    Returns:
        ``StrategyFigures``. The runner multiples are computed from the wheel RoC
        ``R``; ``J_CH = (days per week / R) * (sum(1 / k_i) - 1)`` and the
        coverage follows ``config.coverage_basis`` (``wheel_roc`` module).
    """

    if strategy not in (SINGLE, RUNNER_MULTIPLE):
        raise ValueError(f"unknown cycle stock strategy: {strategy}")
    demands = [member.demand_litres for member in members]
    single = wheel_figures([member.fini_id for member in members], demands,
                           [member.pallet_litres for member in members], [1] * len(members),
                           nominal_lot_litres, effective_batch_litres, config.demand_days, config.productive_weeks)
    if strategy == SINGLE and not classify_members:
        multiples = tuple(MemberMultiple(member.fini_id, None, None, None, 1, "single_roc") for member in members)
    else:
        multiples = member_multiples(members, single.roc_days, effective_batch_litres, config, ratios)
    if strategy == SINGLE:
        multiples = tuple(dataclasses.replace(item, multiple=1) for item in multiples)
        wheel = single
    else:
        # TODO(managed-complexity): open question 4, demand-weighted coverage vs each FINI against the target band.
        wheel = wheel_figures(single.fini_ids, demands, [member.pallet_litres for member in members],
                              [item.multiple for item in multiples], nominal_lot_litres,
                              effective_batch_litres, config.demand_days, config.productive_weeks)
    return StrategyFigures(strategy, wheel.coverage(config.coverage_basis), wheel.j_ch,
                           wheel.fills_per_batch, multiples, wheel)


def eligible_for_multiples(
    members: Sequence[CandidateMember],
    config,
    ratios: Mapping[tuple[str, str, str], float | None],
    batch_litres: float,
) -> bool:
    """Return whether ``optimizer_choice`` should offer a subgroup with runner multiples.

    Args:
        members: The subgroup's FINIs.
        config: Run configuration.
        ratios: ``business_rules.runner_ratios`` of the whole population.
        batch_litres: Effective batch of the subgroup's PV.

    Returns:
        ``True`` for 2+ FINIs that, when ``mixed_groups_only`` is set, span two
        or more runner classes. Whether a multiple above 1 results is checked
        after the coefficients exist (see ``optimization.solver``).
    """

    if len(members) < 2:
        return False
    if not config.cycle_stock_policy.mixed_groups_only:
        return True
    classes = {classify(runner_coverage(member, config, batch_litres), ratios.get((*member.block_key, member.fini_id)),
                        config.runner_thresholds) for member in members}
    return len(classes - {None}) >= 2


def expand_strategy_variants(
    candidates: Sequence[Candidate],
    members: Mapping[tuple[str, str, str], CandidateMember],
    config,
    ratios: Mapping[tuple[str, str, str], float | None],
) -> tuple[Candidate, ...]:
    """Add or substitute ``runner_multiple`` versions according to the policy mode.

    Beam search and pool hashing never see the versions: they are created right
    before coefficients are computed.

    Args:
        candidates: Pool candidates in canonical solver order (all ``single``).
        members: ``{(plant, sefi, fini_id): member}`` of the modeled population.
        config: Run configuration; ``cycle_stock_policy.mode`` decides.
        ratios: ``business_rules.runner_ratios`` of the whole population.

    Returns:
        ``single``: the input unchanged. ``runner_multiple``: every candidate
        with 2+ FINIs replaced by its multiple version. ``optimizer_choice``:
        every candidate, each eligible one followed by its multiple version.
        A multiple version that breaks a hard group rule of the profile (for
        example on ``group.coverage_days``) is left out; in ``runner_multiple``
        mode that group is then unavailable.
    """

    mode = config.cycle_stock_policy.mode
    if mode == SINGLE:
        return tuple(candidates)
    expanded: list[Candidate] = []
    for candidate in candidates:
        if len(candidate.member_ids) < 2:
            expanded.append(candidate)
            continue
        plant, sefi = candidate.block_key
        group = [members[(plant, sefi, fini_id)] for fini_id in candidate.member_ids]
        if mode != RUNNER_MULTIPLE:
            expanded.append(candidate)
            if not eligible_for_multiples(group, config, ratios, candidate.effective_batch_litres):
                continue
        variant = multiple_version(candidate)
        # Pool generation checked the rules on the single figures only.
        if group_allowed(variant, group, config, ratios):
            expanded.append(variant)
    return tuple(expanded)


def _self_check() -> None:
    """Assert the worked example of docs/managed-complexity.md; raises on regression."""

    from production_wheel.schemas import RunConfig

    def member(fini, demand, full):
        return CandidateMember(fini_id=fini, plant="P", sefi="S", eligible_lines=frozenset({"L1"}),
                               demand_litres=demand, pallet_litres=100, package_volume=1,
                               reference_coverage_source_days=full)

    group = [member("P1", 4000, 12), member("P2", 1600, 30), member("P3", 690, 70), member("P4", 160, 300)]
    # 80 demand days / 16 productive weeks = 5 days per week.
    config = RunConfig(cycle_stock_policy={"mode": "runner_multiple"}, demand_days=80, productive_weeks=16)
    ratios = {("P", "S", m.fini_id): round(m.reference_coverage_source_days / 12, 1) for m in group}
    # Effective batch 806.25 L gives a base RoC of exactly 10 days: R = 10, 0.5 batches per week.
    single = strategy_figures(SINGLE, group, 806.25 / 0.9, 806.25, config, ratios)
    multiple = strategy_figures(RUNNER_MULTIPLE, group, 806.25 / 0.9, 806.25, config, ratios)
    assert single.wheel.roc_days == 10 and single.frequency_per_week == 0.5
    assert (single.j_ch, single.coverage_days) == (1.5, 10)
    assert [m.multiple for m in multiple.members] == [1, 2, 2, 4]
    assert [m.runner_class for m in multiple.members] == ["high", "high", "medium", "low"]
    assert multiple.fills_per_batch == 2.25 and multiple.j_ch == 0.625
    assert round(multiple.coverage_days, 2) == 14.29


if __name__ == "__main__":
    _self_check()
    print("cycle stock self-check passed")
