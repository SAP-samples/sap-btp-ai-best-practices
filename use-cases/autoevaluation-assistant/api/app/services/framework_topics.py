"""Reviewed titles keyed by canonical question ID and supported language."""


def topic_title_for(question_id: str, language: str) -> str:
    """Return the approved localized title for one canonical question.

    Inputs:
        question_id: Canonical assessment question identity.
        language: Supported language code, ``en`` or ``it``.

    Outputs:
        str: Exact reviewed topic title.

    Raises:
        ValueError: If the question or language has no approved title.
    """

    titles = CANONICAL_TOPIC_TITLES.get(question_id)
    if titles is None or language not in titles:
        raise ValueError(
            f"No canonical {language!r} topic title for question {question_id}"
        )
    return titles[language]


def topic_translation_rows(question_ids: list[str]) -> list[dict[str, str]]:
    """Build deterministic HANA translation rows for canonical questions.

    Inputs:
        question_ids: Canonical question IDs in framework display order.

    Outputs:
        list[dict[str, str]]: English then Italian title rows per question.
    """

    return [
        {
            "question_id": question_id,
            "language": language,
            "topic_title": topic_title_for(question_id, language),
        }
        for question_id in question_ids
        for language in ("en", "it")
    ]
