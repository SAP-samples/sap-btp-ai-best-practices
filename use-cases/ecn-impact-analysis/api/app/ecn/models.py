# ---------------------------------------------------------------------------
# Canonical UUID guard
# ---------------------------------------------------------------------------


def canonical_uuid(value: str | UUID) -> str:
    """Return a lowercase hyphenated UUID string; reject alternate textual forms.

    Accepts a ``UUID`` object or a string already in canonical form
    (``xxxxxxxx-xxxx-xxxx-xxxx-xxxxxxxxxxxx``).  Strings in the alternate
    Python-accepted forms (braced, bare hex, URN) are rejected so that every
    stored identifier is round-trip safe and unambiguous.

    Args:
        value: A ``UUID`` object or a canonical UUID string.

    Returns:
        The canonical lowercase hyphenated UUID string.

    Raises:
        ValueError: If ``value`` is a string that is not in canonical UUID form.
    """
    try:
        parsed = value if isinstance(value, UUID) else UUID(value)
    except (AttributeError, ValueError) as exc:
        raise ValueError("identifier must be a canonical UUID string") from exc
    rendered = str(parsed)
    if isinstance(value, str) and value != rendered:
        raise ValueError("identifier must be a canonical UUID string")
    return rendered


def _validate_hash_or_uuid(value: str, prefix: str, field_name: str) -> None:
    """Validate a deterministic prefixed hash while admitting legacy UUID rows."""
    suffix = value.removeprefix(prefix)
    if (
        value.startswith(prefix)
        and len(suffix) == 16
        and all(character in "0123456789abcdef" for character in suffix)
    ):
        return
    try:
        canonical_uuid(value)
    except ValueError as exc:
        raise ValueError(
            f"{field_name} must be {prefix}<16 lowercase hex characters>"
        ) from exc


