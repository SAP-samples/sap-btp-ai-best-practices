@dataclass(frozen=True)
class ChangeCandidate:
    """Represent one candidate part-change pair derived from ECN evidence.

    ``candidate_id`` is normally the deterministic ``C-<16 lowercase hex>``
    format; canonical UUIDs remain readable for pre-Phase-2 stored records.
    ``affected_object_ids`` and ``resulting_object_ids`` contain canonical
    UUIDs that reference ``NormalizedSourceObject.source_object_id`` values.

    Args:
        candidate_id: Stable deterministic candidate identifier.
        kind: Structural relationship kind between affected and resulting
            objects.
        affected_object_ids: Tuple of canonical UUIDs for affected objects.
        resulting_object_ids: Tuple of canonical UUIDs for resulting objects.
        source_paths: Tuple of JSON-pointer paths that support this candidate.
        qualifiers: Tuple of derivation quality flags.
        explicit_relation_text: Raw relation text from the source when the
            kind is ``EXPLICIT_SOURCE_RELATION``; ``None`` otherwise.
    """

    candidate_id: str
    kind: ChangeCandidateKind
    affected_object_ids: tuple[str, ...]
    resulting_object_ids: tuple[str, ...]
    source_paths: tuple[str, ...]
    qualifiers: tuple[str, ...]
    explicit_relation_text: str | None

    def __post_init__(self) -> None:
        """Validate stable identity and canonical member object UUIDs."""
        _validate_hash_or_uuid(self.candidate_id, "C-", "candidate_id")
        for oid in self.affected_object_ids:
            canonical_uuid(oid)
        for oid in self.resulting_object_ids:
            canonical_uuid(oid)


@dataclass(frozen=True)
class EvidenceSource:
    """Point to the exact artifact location that supports one evidence item.

    At most one of the location discriminators (``json_path``,
    ``sheet_name``/``bom_row_id``) is meaningful for a given source; the
    irrelevant fields are ``None``.

    Args:
        artifact_id: Canonical UUID string of the referenced artifact.
        artifact_kind: File-type classification of the referenced artifact.
        json_path: JSON-pointer path within the artifact; ``None`` for
            workbook sources.
        sheet_name: Worksheet name; ``None`` for JSON sources.
        bom_row_id: Canonical UUID of the specific BOM row; ``None`` when
            referencing the artifact as a whole.
        source_row_number: 1-based row number in the source sheet; ``None``
            when not applicable.
    """

    artifact_id: str
    artifact_kind: ArtifactKind
    json_path: str | None
    sheet_name: str | None
    bom_row_id: str | None
    source_row_number: int | None

    def __post_init__(self) -> None:
        """Validate artifact identity UUID and optional BOM row UUID."""
        canonical_uuid(self.artifact_id)
        if self.bom_row_id is not None:
            canonical_uuid(self.bom_row_id)


