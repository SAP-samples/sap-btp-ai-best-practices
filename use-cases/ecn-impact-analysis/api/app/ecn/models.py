    object_type: str | None
    revision: str | None
    version: str | None
    state: str | None
    created_on: str | None
    last_modified: str | None
    source_subtype: str | None
    relationship_values: dict[str, JsonValue]
    raw_object: dict[str, JsonValue]
    is_technical_wtpart: bool
    quality_qualifiers: tuple[str, ...]

