@dataclass(frozen=True)
class ParsedBomWorkbook:
    """Hold all normalized BOM rows parsed from one workbook artifact.

    ``sheet_roles`` maps each recognized ``BomKind`` to the sheet name it
    was sourced from.  ``row_count`` and ``cell_count`` are nonnegative
    summary counters.

    Args:
        rows: Tuple of all normalized BOM rows in sheet/row order.
        sheet_roles: Mapping from BOM kind to the originating sheet name.
        row_count: Total number of data rows parsed (>= 0).
        cell_count: Total number of non-empty cells parsed (>= 0).
        quality_qualifiers: Tuple of workbook-level quality flags.
    """

    rows: tuple[BomRow, ...]
    sheet_roles: dict[BomKind, str]
    row_count: int
    cell_count: int
    quality_qualifiers: tuple[str, ...]

    def __post_init__(self) -> None:
        """Validate nonnegative row and cell counts."""
        if self.row_count < 0:
            raise ValueError("row_count must be a nonnegative integer")
        if self.cell_count < 0:
            raise ValueError("cell_count must be a nonnegative integer")
